-- ─── Kimlik ve hesap ────────────────────────────────────────────────────────

CREATE TABLE users (
    id                uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name         varchar(120) NOT NULL,
    email             varchar(254) NOT NULL,
    phone             varchar(16)  UNIQUE CHECK (phone ~ '^\+[1-9][0-9]{7,14}$'),
    password_hash     varchar(100) NOT NULL,
    locale            varchar(2)   NOT NULL DEFAULT 'tr' CHECK (locale IN ('tr', 'en')),
    status            varchar(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELETED')),
    last_mode         varchar(16)  NOT NULL DEFAULT 'CUSTOMER' CHECK (last_mode IN ('CUSTOMER', 'PRO')),
    is_admin          boolean      NOT NULL DEFAULT false,
    kvkk_accepted_at  timestamptz,
    terms_accepted_at timestamptz,
    deleted_at        timestamptz,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

CREATE TABLE refresh_tokens (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  varchar(64) NOT NULL UNIQUE,
    family_id   uuid        NOT NULL,
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz,
    replaced_by uuid        REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    user_agent  varchar(255),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE password_reset_codes (
    id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash  varchar(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    attempts   integer     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    used_at    timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_password_reset_codes_user ON password_reset_codes (user_id, created_at DESC);

CREATE TABLE login_attempts (
    id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    identifier_hash varchar(64) NOT NULL,
    ip              varchar(64),
    success         boolean     NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_login_attempts_identifier ON login_attempts (identifier_hash, created_at DESC);

CREATE TABLE addresses (
    id                  uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label               varchar(40)  NOT NULL,
    district_id         integer      NOT NULL REFERENCES districts (id),
    neighborhood        varchar(120) NOT NULL,
    line_full_encrypted text         NOT NULL,
    door_note_encrypted text,
    is_default          boolean      NOT NULL DEFAULT false,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_addresses_user ON addresses (user_id);
CREATE UNIQUE INDEX ux_addresses_one_default ON addresses (user_id) WHERE is_default;

-- ─── Medya ──────────────────────────────────────────────────────────────────

CREATE TABLE media (
    id           uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id     uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose      varchar(24)  NOT NULL CHECK (purpose IN
                     ('REQUEST_PHOTO', 'JOB_PHOTO', 'CHAT', 'COMPLAINT', 'PRO_DOCUMENT', 'AVATAR')),
    storage_key  varchar(255) NOT NULL UNIQUE,
    content_type varchar(80)  NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'application/pdf')),
    size_bytes   bigint       NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 5242880
                     AND (purpose = 'PRO_DOCUMENT' OR size_bytes <= 1572864)),
    width        integer,
    height       integer,
    sha256       varchar(64),
    created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_media_owner ON media (owner_id);

-- ─── Usta ───────────────────────────────────────────────────────────────────

CREATE TABLE pro_profiles (
    user_id            uuid          PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    business_name      varchar(120)  NOT NULL,
    bio                text,
    experience_years   integer       NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
    review_status      varchar(20)   NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (review_status IN
                           ('PENDING_REVIEW', 'APPROVED', 'NEEDS_DOCUMENTS', 'REJECTED', 'SUSPENDED')),
    review_note        text,
    availability       varchar(10)   NOT NULL DEFAULT 'ACTIVE' CHECK (availability IN ('ACTIVE', 'ON_BREAK')),
    rating_avg         numeric(3, 2) CHECK (rating_avg BETWEEN 1 AND 5),
    rating_count       integer       NOT NULL DEFAULT 0 CHECK (rating_count >= 0),
    completed_jobs     integer       NOT NULL DEFAULT 0 CHECK (completed_jobs >= 0),
    cancellation_count integer       NOT NULL DEFAULT 0 CHECK (cancellation_count >= 0),
    warning_count      integer       NOT NULL DEFAULT 0 CHECK (warning_count >= 0),
    approved_at        timestamptz,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),
    version            bigint        NOT NULL DEFAULT 0
);

CREATE TABLE pro_categories (
    pro_id      uuid        NOT NULL REFERENCES pro_profiles (user_id) ON DELETE CASCADE,
    category_id varchar(32) NOT NULL REFERENCES categories (id),
    PRIMARY KEY (pro_id, category_id)
);

CREATE TABLE pro_districts (
    pro_id      uuid    NOT NULL REFERENCES pro_profiles (user_id) ON DELETE CASCADE,
    district_id integer NOT NULL REFERENCES districts (id),
    PRIMARY KEY (pro_id, district_id)
);

CREATE TABLE pro_working_hours (
    id             uuid    PRIMARY KEY DEFAULT gen_random_uuid(),
    pro_id         uuid    NOT NULL REFERENCES pro_profiles (user_id) ON DELETE CASCADE,
    weekday        integer NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    start_time     time    NOT NULL,
    end_time       time    NOT NULL,
    accepts_urgent boolean NOT NULL DEFAULT false,
    CHECK (end_time > start_time)
);
CREATE INDEX ix_pro_working_hours_pro ON pro_working_hours (pro_id);

CREATE TABLE pro_documents (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    pro_id      uuid        NOT NULL REFERENCES pro_profiles (user_id) ON DELETE CASCADE,
    type        varchar(20) NOT NULL CHECK (type IN ('IDENTITY', 'TRADE_CERT', 'TAX', 'CRIMINAL_RECORD')),
    media_id    uuid        NOT NULL REFERENCES media (id),
    status      varchar(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    reviewed_by uuid        REFERENCES users (id),
    reviewed_at timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_pro_documents_pro ON pro_documents (pro_id);

-- ─── Talep, teklif, iş ──────────────────────────────────────────────────────

CREATE TABLE service_requests (
    id                uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    public_code       varchar(16)  NOT NULL UNIQUE CHECK (public_code ~ '^BD-[0-9]{5,}$'),
    customer_id       uuid         NOT NULL REFERENCES users (id),
    category_id       varchar(32)  NOT NULL REFERENCES categories (id),
    urgency           varchar(8)   NOT NULL CHECK (urgency IN ('URGENT', 'PLANNED')),
    preferred_from    timestamptz,
    preferred_to      timestamptz,
    title             varchar(120) NOT NULL,
    description       text         NOT NULL CHECK (char_length(description) >= 20),
    district_id       integer      NOT NULL REFERENCES districts (id),
    neighborhood      varchar(120) NOT NULL,
    address_id        uuid         REFERENCES addresses (id) ON DELETE SET NULL,
    status            varchar(12)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'ASSIGNED', 'CANCELLED', 'EXPIRED')),
    matched_pro_count integer      NOT NULL DEFAULT 0 CHECK (matched_pro_count >= 0),
    expires_at        timestamptz  NOT NULL,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    version           bigint       NOT NULL DEFAULT 0,
    CHECK (preferred_to IS NULL OR preferred_from IS NULL OR preferred_to > preferred_from)
);
CREATE INDEX ix_service_requests_customer ON service_requests (customer_id, created_at DESC);
CREATE INDEX ix_service_requests_feed ON service_requests (status, category_id, district_id);

CREATE TABLE request_photos (
    request_id uuid    NOT NULL REFERENCES service_requests (id) ON DELETE CASCADE,
    media_id   uuid    NOT NULL REFERENCES media (id),
    sort_order integer NOT NULL CHECK (sort_order BETWEEN 0 AND 4),   -- en fazla 5 fotoğraf
    PRIMARY KEY (request_id, media_id),
    UNIQUE (request_id, sort_order)
);

CREATE TABLE request_answers (
    request_id   uuid         NOT NULL REFERENCES service_requests (id) ON DELETE CASCADE,
    question_key varchar(60)  NOT NULL,
    answer       varchar(500) NOT NULL,
    PRIMARY KEY (request_id, question_key)
);

CREATE TABLE offers (
    id               uuid           PRIMARY KEY DEFAULT gen_random_uuid(),
    public_code      varchar(40)    NOT NULL UNIQUE,
    request_id       uuid           NOT NULL REFERENCES service_requests (id),
    pro_id           uuid           NOT NULL REFERENCES pro_profiles (user_id),
    labor_amount     numeric(12, 2) NOT NULL CHECK (labor_amount > 0),
    materials_amount numeric(12, 2) NOT NULL CHECK (materials_amount >= 0),
    total_amount     numeric(12, 2) NOT NULL CHECK (total_amount > 0),
    arrival_from     timestamptz    NOT NULL,
    arrival_to       timestamptz    NOT NULL,
    warranty_months  integer        NOT NULL CHECK (warranty_months IN (0, 3, 6, 12)),
    note             varchar(1000),
    status           varchar(12)    NOT NULL DEFAULT 'PENDING' CHECK (status IN
                         ('PENDING', 'ACCEPTED', 'SUPERSEDED', 'DECLINED', 'WITHDRAWN', 'EXPIRED')),
    valid_until      timestamptz    NOT NULL,
    decline_reason   varchar(500),
    created_at       timestamptz    NOT NULL DEFAULT now(),
    updated_at       timestamptz    NOT NULL DEFAULT now(),
    version          bigint         NOT NULL DEFAULT 0,
    CHECK (total_amount = labor_amount + materials_amount),
    CHECK (arrival_to > arrival_from)
);
CREATE UNIQUE INDEX ux_offers_one_pending_per_pro ON offers (request_id, pro_id) WHERE status = 'PENDING';
CREATE INDEX ix_offers_request ON offers (request_id);
CREATE INDEX ix_offers_pro ON offers (pro_id, status);

CREATE TABLE offer_items (
    id          uuid           PRIMARY KEY DEFAULT gen_random_uuid(),
    offer_id    uuid           NOT NULL REFERENCES offers (id) ON DELETE CASCADE,
    kind        varchar(10)    NOT NULL CHECK (kind IN ('LABOR', 'MATERIAL')),
    description varchar(200)   NOT NULL,
    quantity    numeric(10, 2) NOT NULL CHECK (quantity > 0),
    unit_price  numeric(12, 2) NOT NULL CHECK (unit_price >= 0)
);
CREATE INDEX ix_offer_items_offer ON offer_items (offer_id);

CREATE TABLE jobs (
    id                    uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    request_id            uuid         NOT NULL REFERENCES service_requests (id),
    offer_id              uuid         NOT NULL UNIQUE REFERENCES offers (id),
    customer_id           uuid         NOT NULL REFERENCES users (id),
    pro_id                uuid         NOT NULL REFERENCES pro_profiles (user_id),
    status                varchar(24)  NOT NULL DEFAULT 'AWAITING_APPOINTMENT' CHECK (status IN
                              ('AWAITING_APPOINTMENT', 'SCHEDULED', 'ARRIVED', 'IN_PROGRESS', 'WORK_FINISHED',
                               'COMPLETED', 'DISPUTED', 'CANCELLED', 'RESOLVED')),
    status_before_dispute varchar(24)  CHECK (status_before_dispute IN
                              ('SCHEDULED', 'ARRIVED', 'IN_PROGRESS', 'WORK_FINISHED')),
    scheduled_from        timestamptz,
    scheduled_to          timestamptz,
    arrived_at            timestamptz,
    started_at            timestamptz,
    finished_at           timestamptz,
    completed_at          timestamptz,
    cancelled_at          timestamptz,
    cancelled_by          varchar(10)  CHECK (cancelled_by IN ('CUSTOMER', 'PRO', 'ADMIN')),
    cancel_reason         varchar(500),
    auto_complete_at      timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    version               bigint       NOT NULL DEFAULT 0
);
-- Talep başına tek aktif iş; usta iptalinden (CANCELLED) sonra yeni iş açılabilir.
CREATE UNIQUE INDEX ux_jobs_one_active_per_request ON jobs (request_id) WHERE status <> 'CANCELLED';
CREATE INDEX ix_jobs_customer ON jobs (customer_id, status);
CREATE INDEX ix_jobs_pro ON jobs (pro_id, status);
CREATE INDEX ix_jobs_auto_complete ON jobs (auto_complete_at) WHERE status = 'WORK_FINISHED';

CREATE TABLE appointment_proposals (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id      uuid        NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    proposed_by varchar(10) NOT NULL CHECK (proposed_by IN ('CUSTOMER', 'PRO')),
    slot_from   timestamptz NOT NULL,
    slot_to     timestamptz NOT NULL,
    status      varchar(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'SUPERSEDED', 'REJECTED')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (slot_to > slot_from)
);
CREATE UNIQUE INDEX ux_appointment_one_pending ON appointment_proposals (job_id) WHERE status = 'PENDING';

CREATE TABLE job_events (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id      uuid        NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    actor_id    uuid        REFERENCES users (id),
    type        varchar(20) NOT NULL CHECK (type IN ('STATUS_CHANGED', 'NOTE', 'PHOTO')),
    from_status varchar(24),
    to_status   varchar(24),
    note        varchar(1000),
    media_id    uuid        REFERENCES media (id),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_job_events_job ON job_events (job_id, created_at);

-- ─── Ödeme (yardımcı defter; escrow_payment sonraki dalgada genişler) ───────

-- payment_ref, escrow_payment.ref ile eşleşir. Tablo genişletilip yeniden adlandırılana kadar yabancı anahtar yok.
CREATE TABLE payout_ledger (
    id          uuid           PRIMARY KEY DEFAULT gen_random_uuid(),
    payment_ref varchar(255)   NOT NULL,
    pro_id      uuid           REFERENCES pro_profiles (user_id),
    amount      numeric(12, 2) NOT NULL CHECK (amount > 0),
    kind        varchar(12)    NOT NULL CHECK (kind IN ('PAYOUT', 'COMMISSION', 'REFUND')),
    created_at  timestamptz    NOT NULL DEFAULT now()
);
CREATE INDEX ix_payout_ledger_payment ON payout_ledger (payment_ref);
CREATE INDEX ix_payout_ledger_pro ON payout_ledger (pro_id, created_at DESC);

-- ─── İletişim ve değerlendirme ──────────────────────────────────────────────

CREATE TABLE messages (
    id         bigserial   PRIMARY KEY,
    job_id     uuid        NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    sender_id  uuid        NOT NULL REFERENCES users (id),
    body       varchar(2000),
    media_id   uuid        REFERENCES media (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (body IS NOT NULL OR media_id IS NOT NULL)
);
CREATE INDEX ix_messages_job ON messages (job_id, id);

CREATE TABLE message_reads (
    job_id       uuid   NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    user_id      uuid   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    last_read_id bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (job_id, user_id)
);

CREATE TABLE reviews (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id       uuid        NOT NULL UNIQUE REFERENCES jobs (id),
    customer_id  uuid        NOT NULL REFERENCES users (id),
    pro_id       uuid        NOT NULL REFERENCES pro_profiles (user_id),
    rating       integer     NOT NULL CHECK (rating BETWEEN 1 AND 5),
    tags         text[]      NOT NULL DEFAULT '{}',
    comment      varchar(1000),
    is_anonymous boolean     NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_reviews_pro ON reviews (pro_id, created_at DESC);

CREATE TABLE complaints (
    id            uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    public_code   varchar(16)  NOT NULL UNIQUE CHECK (public_code ~ '^SK-[0-9]{4,}$'),
    job_id        uuid         NOT NULL REFERENCES jobs (id),
    customer_id   uuid         NOT NULL REFERENCES users (id),
    pro_id        uuid         NOT NULL REFERENCES pro_profiles (user_id),
    reason        varchar(120) NOT NULL,
    description   text         NOT NULL CHECK (char_length(description) >= 20),
    status        varchar(10)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_REVIEW', 'RESOLVED', 'DISMISSED')),
    decision      varchar(16)  CHECK (decision IN ('FULL_REFUND', 'SPLIT_50_50', 'RELEASE_TO_PRO')),
    decision_note text,
    decided_by    uuid         REFERENCES users (id),
    decided_at    timestamptz,
    warn_pro      boolean      NOT NULL DEFAULT false,
    suspend_pro   boolean      NOT NULL DEFAULT false,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now()
);
-- Açık şikayet iş başına bir tane.
CREATE UNIQUE INDEX ux_complaints_one_open_per_job ON complaints (job_id) WHERE status IN ('OPEN', 'IN_REVIEW');

CREATE TABLE complaint_evidence (
    complaint_id uuid NOT NULL REFERENCES complaints (id) ON DELETE CASCADE,
    media_id     uuid NOT NULL REFERENCES media (id),
    PRIMARY KEY (complaint_id, media_id)
);

CREATE TABLE notifications (
    id           uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         varchar(40)  NOT NULL,
    title_key    varchar(80)  NOT NULL,
    body_key     varchar(80)  NOT NULL,
    params       jsonb        NOT NULL DEFAULT '{}'::jsonb,
    target_route varchar(200),
    read_at      timestamptz,
    created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_notifications_user ON notifications (user_id, created_at DESC);

CREATE TABLE device_tokens (
    id         uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    platform   varchar(10)  NOT NULL CHECK (platform IN ('IOS', 'ANDROID', 'WEB')),
    token      varchar(512) NOT NULL UNIQUE,
    updated_at timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_device_tokens_user ON device_tokens (user_id);

CREATE TABLE admin_actions (
    id          uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    admin_id    uuid         NOT NULL REFERENCES users (id),
    action      varchar(60)  NOT NULL,
    target_type varchar(40)  NOT NULL,
    target_id   varchar(64)  NOT NULL,
    note        text,
    created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_admin_actions_target ON admin_actions (target_type, target_id);
